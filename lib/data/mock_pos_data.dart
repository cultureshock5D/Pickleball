  static String generateInvoiceNumber() {
    final todayStr = DateFormat('yyyyMMdd').format(DateTime.now());
    final rand = Random().nextInt(90000) + 10000;
    return 'SI-$todayStr-$rand';
  }

  static PosTransactionModel recordTransaction({
    required String cashierId,
    required String? cashierName,
    required String? customerName,
    required String? customerTin,
    required String discountType,
    required String? discountIdNumber,
    required BirTaxBreakdown taxBreakdown,
    required String paymentMethod,
    required List<Map<String, dynamic>> items,
  }) {
    final invoiceNumber = generateInvoiceNumber();
    final txId = 'tx-pos-${DateTime.now().millisecondsSinceEpoch}';

    final transactionItems = items.map((item) {
      final prodId = item['product_id'] as String;
      final qty = item['quantity'] as int;
      final price = (item['price_at_time'] as num).toDouble();
      final name = item['product_name'] as String? ?? 'Item';

      // Decrement stock in memory
      final pIndex = _products.indexWhere((p) => p.id == prodId);
      if (pIndex != -1) {
        final current = _products[pIndex];
        final newStock = max(0, current.stockLevel - qty);
        _products[pIndex] = current.copyWith(stockLevel: newStock);
      }

      return PosTransactionItemModel(
        id: 'item-${DateTime.now().millisecondsSinceEpoch}-${Random().nextInt(1000)}',
        transactionId: txId,
        productId: prodId,
        productName: name,
        quantity: qty,
        priceAtTime: price,
      );
    }).toList();

    final tx = PosTransactionModel(
      id: txId,
      invoiceNumber: invoiceNumber,
      cashierId: cashierId,
      cashierName: cashierName ?? 'Cashier Staff',
      customerName: customerName,
      customerTin: customerTin,
      discountType: discountType,
      discountIdNumber: discountIdNumber,
      grossAmount: taxBreakdown.grossSubtotal,
      discountAmount: taxBreakdown.discountAmount,
      vatableSales: taxBreakdown.vatableSales,
      vatAmount: taxBreakdown.vatAmount,
      vatExemptSales: taxBreakdown.vatExemptSales,
      totalAmount: taxBreakdown.netPayable,
      paymentMethod: paymentMethod,
      createdAt: DateTime.now(),
      items: transactionItems,
    );

    _transactions.insert(0, tx);
    return tx;
  }

  static bool voidTransaction({
    required String transactionId,
    required String voidReason,
    required String voidedBy,
  }) {
    final index = _transactions.indexWhere((t) => t.id == transactionId);
    if (index == -1) return false;

    final tx = _transactions[index];
    if (tx.isVoided) return false;

    // Restore stock
    for (final item in tx.items) {
      final pIndex = _products.indexWhere((p) => p.id == item.productId);
      if (pIndex != -1) {
        final current = _products[pIndex];
        _products[pIndex] = current.copyWith(
          stockLevel: current.stockLevel + item.quantity,
        );
      }
    }

    _transactions[index] = tx.copyWith(
      status: 'voided',
      voidReason: voidReason,
      voidedAt: DateTime.now(),
      voidedBy: voidedBy,
    );

    return true;
  }
